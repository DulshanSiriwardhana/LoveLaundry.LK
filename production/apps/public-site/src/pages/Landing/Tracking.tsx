import { useCallback, useEffect, useRef, useState } from "react";
import {
    RiCheckLine,
    RiCloseCircleLine,
    RiHashtag,
    RiLoader4Line,
    RiQrCodeLine,
    RiSearchLine,
    RiTimeLine,
    RiTruckLine,
} from "react-icons/ri";

import { useLanguage, type Language } from "../../i18n";
import {
    fetchTracking,
    isTrackingConfigured,
    TrackingError,
    type TrackingErrorKind,
    type TrackingHistoryEntry,
    type TrackingResult,
} from "../../lib/trackingApi";
import SectionHeader from "./SectionHeader";

const STATUS_KEYS: Record<string, string> = {
    draft: "statusDraft",
    received: "statusReceived",
    washing: "statusWashing",
    pressing: "statusPressing",
    folding: "statusFolding",
    packing: "statusPacking",
    ready: "statusReady",
    out_for_delivery: "statusOutForDelivery",
    delivered: "statusDelivered",
    cancelled: "statusCancelled",
};

const formatDate = (value: string | null | undefined, lang: Language) => {
    if (!value) return "—";
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return value;
    return new Intl.DateTimeFormat(lang === "sin" ? "si-LK" : "en-GB", {
        dateStyle: "medium",
        timeStyle: "short",
    }).format(date);
};

const Tracking = () => {
    const { t, lang } = useLanguage();
    const [query, setQuery] = useState("");
    const [result, setResult] = useState<TrackingResult | null>(null);
    const [errorKind, setErrorKind] = useState<TrackingErrorKind | null>(null);
    const [loading, setLoading] = useState(false);
    const requestRef = useRef(0);

    const lookup = useCallback(async (raw: string) => {
        const requestId = ++requestRef.current;
        setLoading(true);
        setErrorKind(null);
        setResult(null);

        try {
            const data = await fetchTracking(raw);
            if (requestRef.current === requestId) setResult(data);
        } catch (error) {
            if (requestRef.current !== requestId) return;
            setErrorKind(
                error instanceof TrackingError ? error.kind : "unavailable",
            );
        } finally {
            if (requestRef.current === requestId) setLoading(false);
        }
    }, []);

    // QR codes generated by the back office point at /track?tag=CODE. The
    // SPA rewrite serves index.html for that path, so read the query here.
    useEffect(() => {
        const params = new URLSearchParams(window.location.search);
        const initial =
            params.get("tag") || params.get("order") || params.get("id");
        if (!initial) return;

        setQuery(initial);
        void lookup(initial);
        window.requestAnimationFrame(() => {
            document.getElementById("track")?.scrollIntoView({
                behavior: "smooth",
                block: "start",
            });
        });
    }, [lookup]);

    const timeline: TrackingHistoryEntry[] = result?.status_history ?? [];

    const statusLabel = (status: string) => {
        const key = STATUS_KEYS[status];
        return key ? t(key) : status.replaceAll("_", " ");
    };

    return (
        <section
            id="track"
            aria-labelledby="track-title"
            className="
                relative
                overflow-hidden
                bg-surface-muted
                px-4
                py-12
                sm:px-6
                sm:py-16
                lg:px-8
                lg:py-20
            "
        >
            <div
                aria-hidden="true"
                className="
                    pointer-events-none
                    absolute
                    inset-0
                    opacity-[0.05]
                    bg-[radial-gradient(circle,var(--color-ink)_1px,transparent_1px)]
                    bg-[length:24px_24px]
                "
            />

            <div className="relative mx-auto w-full max-w-[1440px]">
                <SectionHeader
                    titleId="track-title"
                    badge={t("trackBadge")}
                    main={t("trackTitleMain")}
                    highlight={t("trackTitleHighlight")}
                    description={t("trackDescription")}
                    centered
                />

                <div className="mx-auto mt-10 w-full max-w-3xl sm:mt-12">
                    <form
                        onSubmit={(event) => {
                            event.preventDefault();
                            void lookup(query);
                        }}
                        className="
                            rounded-3xl
                            border
                            border-line
                            bg-surface
                            p-5
                            shadow-[0_12px_36px_rgba(var(--shadow-rgb),0.08)]
                            sm:p-7
                        "
                    >
                        <label
                            htmlFor="tracking-code"
                            className="text-sm font-bold text-ink"
                        >
                            {t("trackLabel")}
                        </label>

                        <div className="mt-3 flex flex-col gap-3 sm:flex-row">
                            <div className="relative flex-1">
                                <RiQrCodeLine
                                    aria-hidden="true"
                                    className="
                                        pointer-events-none
                                        absolute
                                        left-4
                                        top-1/2
                                        h-5
                                        w-5
                                        -translate-y-1/2
                                        text-faint
                                    "
                                />
                                <input
                                    id="tracking-code"
                                    name="tracking-code"
                                    type="text"
                                    value={query}
                                    onChange={(event) =>
                                        setQuery(event.target.value)
                                    }
                                    placeholder={t("trackPlaceholder")}
                                    autoComplete="off"
                                    spellCheck={false}
                                    required
                                    className="
                                        h-13
                                        w-full
                                        rounded-xl
                                        border
                                        border-line-strong
                                        bg-surface-muted
                                        pl-12
                                        pr-4
                                        text-sm
                                        font-semibold
                                        text-ink
                                        outline-none
                                        transition
                                        placeholder:font-normal
                                        placeholder:text-faint
                                        focus:border-brand
                                        focus:ring-2
                                        focus:ring-brand/25
                                    "
                                />
                            </div>

                            <button
                                type="submit"
                                disabled={loading || !query.trim()}
                                className="
                                    flex
                                    h-13
                                    shrink-0
                                    items-center
                                    justify-center
                                    gap-2.5
                                    rounded-xl
                                    bg-brand
                                    px-7
                                    text-sm
                                    font-bold
                                    text-on-dark
                                    shadow-[0_8px_24px_rgba(var(--brand-rgb),0.28)]
                                    transition
                                    hover:bg-brand-dark
                                    disabled:cursor-not-allowed
                                    disabled:opacity-60
                                "
                            >
                                {loading ? (
                                    <RiLoader4Line className="h-4 w-4 animate-spin" />
                                ) : (
                                    <RiSearchLine className="h-4 w-4" />
                                )}
                                {loading
                                    ? t("trackTracking")
                                    : t("trackButton")}
                            </button>
                        </div>

                        <p className="mt-3 text-xs leading-5 text-faint">
                            {t("trackQrHint")}
                            {!isTrackingConfigured() && (
                                <span className="mt-1 block font-semibold text-brand">
                                    {t("trackErrorConfig")}
                                </span>
                            )}
                        </p>
                    </form>

                    <div aria-live="polite" className="min-h-4">
                        {errorKind && (
                            <div
                                role="alert"
                                className="
                                    mt-5
                                    flex
                                    items-start
                                    gap-3
                                    rounded-2xl
                                    border
                                    border-danger-border
                                    bg-danger-soft
                                    p-4
                                    text-sm
                                    font-semibold
                                    text-ink
                                "
                            >
                                <RiCloseCircleLine className="mt-0.5 h-5 w-5 shrink-0 text-brand" />
                                <span>
                                    {t(
                                        errorKind === "config"
                                            ? "trackErrorConfig"
                                            : errorKind === "not_found"
                                              ? "trackErrorNotFound"
                                              : "trackErrorUnavailable",
                                    )}
                                </span>
                            </div>
                        )}

                        {result && (
                            <div
                                className="
                                    mt-5
                                    overflow-hidden
                                    rounded-3xl
                                    border
                                    border-line
                                    bg-surface
                                    shadow-[0_18px_44px_rgba(var(--shadow-rgb),0.1)]
                                "
                            >
                                <div
                                    className="
                                        flex
                                        flex-col
                                        gap-4
                                        border-b
                                        border-line
                                        bg-brand-soft
                                        p-5
                                        sm:flex-row
                                        sm:items-start
                                        sm:justify-between
                                        sm:p-6
                                    "
                                >
                                    <div className="flex items-start gap-3">
                                        <div className="flex h-11 w-11 shrink-0 items-center justify-center rounded-xl bg-brand text-on-dark">
                                            <RiTruckLine className="h-5 w-5" />
                                        </div>
                                        <div>
                                            <div className="text-[10px] font-bold uppercase tracking-[0.16em] text-faint">
                                                {t("trackOrderLabel")}
                                            </div>
                                            <h3
                                                className="
                                                    font-display
                                                    mt-1
                                                    text-lg
                                                    font-bold
                                                    leading-snug
                                                    text-ink
                                                    sm:text-xl
                                                "
                                            >
                                                {result.quotation_title ||
                                                    result.garment_label ||
                                                    t("trackOrderFallback")}
                                            </h3>
                                            <div className="mt-2 flex flex-wrap items-center gap-x-4 gap-y-1 text-xs font-semibold text-muted">
                                                <span className="inline-flex items-center gap-1.5">
                                                    <RiHashtag className="h-3.5 w-3.5 text-brand" />
                                                    {result.garment_label ||
                                                        result.tag ||
                                                        result.code ||
                                                        result.id}
                                                </span>
                                                <span className="inline-flex items-center gap-1.5">
                                                    <RiTimeLine className="h-3.5 w-3.5 text-brand" />
                                                    {t("trackUpdated")}:{" "}
                                                    {formatDate(
                                                        result.updated_at ||
                                                            result.created_at,
                                                        lang,
                                                    )}
                                                </span>
                                            </div>
                                        </div>
                                    </div>

                                    <span
                                        className="
                                            inline-flex
                                            shrink-0
                                            items-center
                                            gap-2
                                            self-start
                                            rounded-full
                                            bg-brand
                                            px-4
                                            py-2
                                            text-xs
                                            font-bold
                                            text-on-dark
                                        "
                                    >
                                        <RiCheckLine className="h-3.5 w-3.5" />
                                        {statusLabel(result.status)}
                                    </span>
                                </div>

                                <div className="p-5 sm:p-6">
                                    <h4 className="text-sm font-bold text-ink">
                                        {t("trackTimelineTitle")}
                                    </h4>

                                    {timeline.length === 0 ? (
                                        <p className="mt-3 text-sm text-muted">
                                            {t("trackNoHistory")}
                                        </p>
                                    ) : (
                                        <ol className="mt-5 space-y-0">
                                            {timeline.map((entry, index) => (
                                                <li
                                                    key={`${entry.changed_at}-${index}`}
                                                    className="relative flex gap-4 pb-6 last:pb-0"
                                                >
                                                    {index < timeline.length - 1 && (
                                                        <span
                                                            aria-hidden="true"
                                                            className="
                                                                absolute
                                                                left-[13px]
                                                                top-7
                                                                h-[calc(100%-1.5rem)]
                                                                w-px
                                                                bg-line-strong
                                                            "
                                                        />
                                                    )}
                                                    <span
                                                        aria-hidden="true"
                                                        className={`
                                                            relative
                                                            z-10
                                                            mt-0.5
                                                            flex
                                                            h-7
                                                            w-7
                                                            shrink-0
                                                            items-center
                                                            justify-center
                                                            rounded-full
                                                            ${
                                                                index === 0
                                                                    ? "bg-brand text-on-dark"
                                                                    : "bg-surface-muted text-faint"
                                                            }
                                                        `}
                                                    >
                                                        <RiCheckLine className="h-3.5 w-3.5" />
                                                    </span>
                                                    <div className="min-w-0 flex-1">
                                                        <div className="flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1">
                                                            <span className="text-sm font-bold text-ink">
                                                                {statusLabel(
                                                                    entry.status,
                                                                )}
                                                            </span>
                                                            <span className="text-xs font-semibold text-faint">
                                                                {formatDate(
                                                                    entry.changed_at,
                                                                    lang,
                                                                )}
                                                            </span>
                                                        </div>
                                                        {entry.note && (
                                                            <p className="mt-1 text-sm leading-6 text-muted">
                                                                {entry.note}
                                                            </p>
                                                        )}
                                                    </div>
                                                </li>
                                            ))}
                                        </ol>
                                    )}

                                    <button
                                        type="button"
                                        onClick={() => {
                                            setResult(null);
                                            setErrorKind(null);
                                            setQuery("");
                                        }}
                                        className="mt-5 text-xs font-bold text-brand underline underline-offset-4"
                                    >
                                        {t("trackAnother")}
                                    </button>
                                </div>
                            </div>
                        )}
                    </div>
                </div>
            </div>
        </section>
    );
};

export default Tracking;
